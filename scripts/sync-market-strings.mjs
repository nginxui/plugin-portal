#!/usr/bin/env node
// Copies the marketplace wording of the catalog site (nginxui/plugins,
// scripts/site-strings.mjs) into web/src/lib/marketStrings.ts, so the store
// preview describes permissions and capabilities with the words users see.
//
// Usage: node scripts/sync-market-strings.mjs [path to site-strings.mjs]

import { writeFileSync } from 'node:fs'
import path from 'node:path'
import process from 'node:process'
import { pathToFileURL } from 'node:url'

const source = path.resolve(process.argv[2] ?? '../plugins/scripts/site-strings.mjs')
const s = await import(pathToFileURL(source).href)

const KEYS = ['by', 'version', 'beta', 'requiresLabel', 'platforms', 'allPlatforms', 'repository', 'homepage', 'screenshots', 'permissions', 'noPermissions', 'onlyHosts', 'noHosts', 'authorNote', 'versions', 'latest', 'information', 'categories', 'about', 'author', 'license', 'provides', 'memory', 'minVersion', 'trust']
const asTemplate = value => typeof value === 'function' ? value('{x}') : value

const labels = {}
for (const locale of s.LOCALES) {
  labels[locale] = {}
  for (const key of KEYS)
    labels[locale][key] = asTemplate(s.STRINGS[locale][key])
}
const templated = obj => Object.fromEntries(Object.entries(obj).map(([k, v]) => [k, asTemplate(v)]))

const out = `// Generated by scripts/sync-market-strings.mjs from the catalog site's
// wording. Do not edit by hand. {x} marks where a value goes.

export const MARKET_LABELS: Record<string, Record<string, any>> = ${JSON.stringify(labels, null, 2)}

export const MARKET_CATEGORIES: Record<string, Record<string, string>> = ${JSON.stringify(s.CATEGORIES, null, 2)}

export const MARKET_CAPABILITIES: Record<string, { label: Record<string, string>, description: Record<string, string> }> = ${JSON.stringify(s.CAPABILITIES, null, 2)}

export const MARKET_PERMISSIONS: Record<string, { label: Record<string, string>, description: Record<string, string> }> = ${JSON.stringify(s.PERMISSIONS, null, 2)}

export const MARKET_CREDENTIALS = ${JSON.stringify({ label: templated(s.CREDENTIALS_PERMISSION.label), description: templated(s.CREDENTIALS_PERMISSION.description) }, null, 2)}

export const MARKET_UNKNOWN = ${JSON.stringify(s.UNKNOWN_PERMISSION, null, 2)}
`
writeFileSync(path.resolve('web/src/lib/marketStrings.ts'), out)
console.log(`wrote web/src/lib/marketStrings.ts from ${source}`)
